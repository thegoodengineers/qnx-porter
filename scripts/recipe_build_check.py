"""Write recipes/BUILD_CHECK.md from a recipe build run, so the table holds only what the builds printed.

    python3 scripts/recipe_build_check.py ~/recipe-check2

The run directory holds results.tsv (name, make exit code or clone-failed/patch-failed, date, one line per
recipe), <name>.log (the make output) and stage/<name>/ (that recipe's INSTALL_ROOT_nto). A failure's reason is
the first error line make printed; artifacts are what `make install` put in the staging folder.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ERR = re.compile(r"error:|Error \d|CMake Error|fatal|No rule to make target|undefined reference")


def artifacts(stage: Path) -> str:
    files = [p for p in stage.rglob("*") if p.is_file()] if stage.is_dir() else []
    libs = sorted(p.name for p in files if re.search(r"\.(a|so)(\.[\d.]+)?$", p.name))
    bins = sorted(p.name for p in files if p.parent.name == "bin")
    heads = sum(p.suffix in (".h", ".hpp", ".hh", ".inl", ".inc") for p in files)
    other = len(files) - len(libs) - len(bins) - heads
    parts = [", ".join(f"`{x}`" for x in libs + bins)] if libs or bins else []
    parts += [f"{heads} headers"] if heads else []
    parts += [f"{other} other files (CMake/pkg-config/docs)"] if other > 0 else []
    return "; ".join(parts) or "none"


def reason(log: Path) -> str:
    if not log.exists():
        return "no build log"
    lines = log.read_text(encoding="utf-8", errors="replace").splitlines()
    for i, ln in enumerate(lines):
        if ERR.search(ln):
            # "CMake Error at <file>:<line> (...):" says where; the message is on the next lines
            msg = " ".join(x.strip() for x in lines[i:i + 3]) if ln.rstrip().endswith(":") else ln.strip()
            return msg.replace(str(Path.home()), "~").replace("|", "\\|")[:200]
    return "make failed; no error line found in the log"


def results(tsv: Path) -> dict[str, list[str]]:
    """name -> [exit code or clone-failed/patch-failed, date]; a rerun of a recipe replaces its earlier line."""
    return {ln.split("\t")[0]: ln.split("\t")[1:] for ln in tsv.read_text(encoding="utf-8").splitlines()}


def result(rc: str, log: Path) -> str:
    return "built" if rc == "0" else {"clone-failed": "failed: git clone failed",
                                      "patch-failed": "failed: qnx.patch did not apply"}.get(rc, f"failed: {reason(log)}")


def main(run: Path) -> int:
    rows = []
    for n, (rc, d) in sorted(results(run / "results.tsv").items(), key=lambda kv: kv[0].lower()):
        got = artifacts(run / "stage" / n) if rc == "0" else "-"
        res = "failed: make install exited 0 but installed nothing" if got == "none" else result(rc, run / f"{n}.log")
        rows.append(f"| {n} | {res} | {got} | {d} |")
    built = sum("| built |" in r for r in rows)
    # the run before the generator fixes, if kept: its failures, with the error each log printed
    first = run / "results-pass1.tsv"
    fails = [f"| {n} | {result(rc, run / 'pass1-logs' / f'{n}.log')} | {d} |"
             for n, (rc, d) in (results(first).items() if first.exists() else []) if rc != "0"]
    earlier = f"""
## Earlier run, before the generator fixes

{len(results(first))} recipes (all but yyjson, wolfssl and flac); these failed and led to the fixes in
`scripts/emit_recipes.py`. The table above is the latest build of every recipe with the current generator.

| library | result | date |
|---|---|---|
""" + "\n".join(fails) + "\n" if fails else ""
    out = ROOT / "recipes" / "BUILD_CHECK.md"
    out.write_text(f"""# Recipe build check

Every recipe built with QNX's recursive make for `nto-x86_64-o` (QNX SDP 8.0, single-job make, one recipe at a
time), from a fresh `git clone --depth 1 --recurse-submodules` of the campaign's tag with the recipe's `qnx.patch`
applied:

    make -C build-files/ports/<name>/nto-x86_64-o install QNX_PROJECT_ROOT=<clone> \\
         INSTALL_ROOT_nto=<stage>/<name> USE_INSTALL_ROOT=true

Generated by `scripts/recipe_build_check.py` from that run's exit codes, logs and staging folders. `nto-aarch64-le`
was not built in this run; yyjson, wolfssl and flac were built for it earlier.

{built} of {len(rows)} built.

| library | result | installed into the staging folder | date |
|---|---|---|---|
""" + "\n".join(rows) + "\n" + earlier, encoding="utf-8", newline="\n")
    print(f"{built}/{len(rows)} built -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]).expanduser()))
