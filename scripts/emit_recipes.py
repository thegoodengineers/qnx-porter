"""Write build-files-style recipes (github.com/qnx-ports/build-files layout) for our CMake ports that qnx-ports
does not have yet, from what the campaign actually built and tested.

    python3 scripts/emit_recipes.py [--qnx-ports results/qnx_ports_names.txt]

Each recipe is recipes/build-files/ports/<name>/ with the same files a hand-made CMake recipe there has:
Makefile, common.mk, qnx.nto.toolchain.cmake, nto-x86_64-o/Makefile, nto-aarch64-le/Makefile, README.md, plus
our qnx.patch and compat headers when the port needed them. The flags and CMake options are the ones the
campaign used (static libraries, the campaign's arguments), so a recipe builds what was tested.
Recipes are written, never sent: opening a pull request on qnx-ports is the team's decision.
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from run_campaign import load  # noqa: E402

OUT = ROOT / "recipes" / "build-files" / "ports"

MAKEFILE = """LIST=OS
ifndef QRECURSE
QRECURSE=recurse.mk
ifdef QCONFIG
QRDIR=$(dir $(QCONFIG))
endif
endif
include $(QRDIR)$(QRECURSE)
"""

TOOLCHAIN = """# QNX SDP 8.0 cross toolchain; CMAKE_SYSTEM_PROCESSOR (x86_64 or aarch64le) comes from common.mk.
if("$ENV{QNX_HOST}" STREQUAL "" OR "$ENV{QNX_TARGET}" STREQUAL "")
    message(FATAL_ERROR "Source qnxsdp-env.sh first: QNX_HOST and QNX_TARGET are not set")
endif()
set(QNX TRUE)
set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_C_COMPILER $ENV{QNX_HOST}/usr/bin/qcc)
set(CMAKE_CXX_COMPILER $ENV{QNX_HOST}/usr/bin/q++)
set(CMAKE_ASM_COMPILER $ENV{QNX_HOST}/usr/bin/qcc)
# binutils are ntox86_64-ar and ntoaarch64-ar: no "le", unlike the -V names
string(REGEX REPLACE "le$" "" NTO_TOOLS "${CMAKE_SYSTEM_PROCESSOR}")
set(CMAKE_AR "$ENV{QNX_HOST}/usr/bin/nto${NTO_TOOLS}-ar" CACHE PATH "archiver")
set(CMAKE_RANLIB "$ENV{QNX_HOST}/usr/bin/nto${NTO_TOOLS}-ranlib" CACHE PATH "ranlib")
set(CMAKE_C_FLAGS "${CMAKE_C_FLAGS} -Vgcc_nto${CMAKE_SYSTEM_PROCESSOR} ${EXTRA_CMAKE_C_FLAGS}" CACHE STRING "c_flags")
set(CMAKE_CXX_FLAGS "${CMAKE_CXX_FLAGS} -Vgcc_nto${CMAKE_SYSTEM_PROCESSOR}_cxx ${EXTRA_CMAKE_CXX_FLAGS}" CACHE STRING "cxx_flags")
set(CMAKE_ASM_FLAGS "${CMAKE_ASM_FLAGS} -Vgcc_nto${CMAKE_SYSTEM_PROCESSOR}" CACHE STRING "asm_flags")
set(CMAKE_EXE_LINKER_FLAGS "${CMAKE_EXE_LINKER_FLAGS} ${EXTRA_CMAKE_LINKER_FLAGS}" CACHE STRING "exe_linker_flags")
set(CMAKE_SHARED_LINKER_FLAGS "${CMAKE_SHARED_LINKER_FLAGS} ${EXTRA_CMAKE_LINKER_FLAGS}" CACHE STRING "so_linker_flags")
set(CMAKE_FIND_ROOT_PATH "$ENV{QNX_TARGET}" "$ENV{QNX_TARGET}/${CMAKE_SYSTEM_PROCESSOR}")
# common.mk's empty rt/dl/pthread archives are in <build>/stubs, outside the SDP. find_library re-roots every
# search path under each root path (CMake 3.22 even an absolute one already inside a root), so the build folder
# is a root and common.mk passes CMAKE_LIBRARY_PATH=/stubs, which finds <build>/stubs/librt.a.
list(APPEND CMAKE_FIND_ROOT_PATH "${CMAKE_BINARY_DIR}")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
"""

COMMON = """# Generated by qnx-porter from its QNX 8.0 port of {name} {tag} (see README.md).
ifndef QCONFIG
QCONFIG=qconfig.mk
endif
include $(QCONFIG)

NAME={name}

QNX_PROJECT_ROOT ?= $(PRODUCT_ROOT)/../../{name}
INSTALL_ROOT ?= $(INSTALL_ROOT_$(OS))
PREFIX ?= /usr/local
BUILD_TESTING ?= OFF
CMAKE_BUILD_TYPE ?= Release
# Static libraries, as in the tested port; set ON for shared ones.
BUILD_SHARED_LIBS ?= OFF

ALL_DEPENDENCIES = {name}_all
.PHONY: {name}_all install check clean

include $(MKFILES_ROOT)/qtargets.mk

# QNX keeps pthread, rt and dl in libc: empty archives let `-lrt` and CMake's library checks succeed.
STUBS = $(CURDIR)/build/stubs
CFLAGS += -I$(INSTALL_ROOT)/$(PREFIX)/include{cflags}
LDFLAGS += -L$(STUBS){ldflags}

# CMAKE_INSTALL_LIBDIR is set because some projects include GNUInstallDirs only when not cross-compiling.
CMAKE_ARGS = -DCMAKE_TOOLCHAIN_FILE=$(PROJECT_ROOT)/qnx.nto.toolchain.cmake \\
             -DCMAKE_SYSTEM_PROCESSOR=$(CPUVARDIR) \\
             -DCMAKE_INSTALL_PREFIX=$(INSTALL_ROOT)/$(CPUVARDIR)/$(PREFIX) \\
             -DCMAKE_INSTALL_INCLUDEDIR=$(INSTALL_ROOT)/$(PREFIX)/include \\
             -DCMAKE_INSTALL_LIBDIR=lib \\
             -DCMAKE_BUILD_TYPE=$(CMAKE_BUILD_TYPE) \\
             -DCMAKE_LIBRARY_PATH=/stubs \\
             -DEXTRA_CMAKE_C_FLAGS="$(CFLAGS)" \\
             -DEXTRA_CMAKE_CXX_FLAGS="$(CFLAGS)" \\
             -DEXTRA_CMAKE_LINKER_FLAGS="$(LDFLAGS)" \\
             -DCMAKE_C_STANDARD_LIBRARIES="{libs}" \\
             -DCMAKE_CXX_STANDARD_LIBRARIES="{libs}" \\
             -DBUILD_SHARED_LIBS=$(BUILD_SHARED_LIBS) \\
             -DBUILD_TESTING=$(BUILD_TESTING){args}

ifndef NO_TARGET_OVERRIDE
{name}_all:
	@mkdir -p $(STUBS) && for l in rt dl pthread; do [ -f $(STUBS)/lib$$l.a ] || printf '!<arch>\\n' > $(STUBS)/lib$$l.a; done
	@cd build && cmake $(CMAKE_ARGS) $(QNX_PROJECT_ROOT){subdir}
	@cd build && cmake --build . $(MAKE_ARGS)

install check: {name}_all
	@cd build && cmake --install .

clean iclean spotless:
	rm -rf build

uninstall:
endif
"""

# Options a recipe needs for `make install` that the campaign, which never installed, did not.
INSTALL_ARGS = {
    # its protoc plugin is host Python and would install into the build machine's site-packages
    "nanopb": ["-Dnanopb_BUILD_GENERATOR=OFF"],
    # its install rules are off by default; without this `make install` installs nothing
    "flatcc": ["-DFLATCC_INSTALL=ON"],
}

FLAGS = re.compile(r'set\(CMAKE_C_FLAGS_INIT "-g ?(?P<c>[^"]*)"\)')
LATE = re.compile(r"# Flags after the project's own .*?: (?P<late>.*)$", re.M)
LIBS = re.compile(r'set\(CMAKE_C_STANDARD_LIBRARIES "(?P<libs>[^"]*)"\)')


def flags(port: Path) -> tuple[list[str], list[str], str]:
    """(cflags, late flags, libs) from the toolchain the campaign generated; compat headers re-pointed."""
    tc = (port / "qnx-toolchain.cmake").read_text(encoding="utf-8")
    c = FLAGS.search(tc)["c"].split()
    c = ["$(PROJECT_ROOT)/qnx-compat/" + Path(x).name if "/qnx-compat/" in x else x for x in c]
    late = [] if (m := LATE.search(tc)) is None or m["late"].strip() == "none" else m["late"].split()
    return c, late, LIBS.search(tc)["libs"]


def readme(lib: dict, r: dict, has_patch: bool, compat: list[str]) -> str:
    tests = (f"{r['tests_passed']}/{r['tests_total']} of its own tests passed" if r.get("tests_total")
             else "its test suite did not run there (see the port's report)")
    rows = "".join(f"| {p['rule']} | {p['reason']} |\n" for p in r.get("patches") or [] if isinstance(p, dict))
    s = f"""# {lib['name']} for QNX 8.0

Generated by [qnx-porter](https://github.com/thegoodengineers/qnx-porter) from its automatic port of
{lib['name']} `{lib['tag']}` ({lib['url']}). On a QNX 8.0 x86_64 target (QEMU) {tests}. Full report:
`ports/{lib['name']}/REPORT.md` in qnx-porter.

## Build
```bash
source ~/qnx800/qnxsdp-env.sh
git clone --depth 1 --recurse-submodules --shallow-submodules --branch {lib['tag']} {lib['url']} {lib['name']}
"""
    if has_patch:
        s += f"git -C {lib['name']} apply ../build-files/ports/{lib['name']}/qnx.patch\n"
    s += f"""QNX_PROJECT_ROOT="$(pwd)/{lib['name']}" make -C build-files/ports/{lib['name']} install JLEVEL=4
```
"""
    if rows:
        s += f"\n## QNX changes, each with its reason\n| rule | reason |\n|---|---|\n{rows}"
    if compat:
        s += f"\nCompat headers in `qnx-compat/` ({', '.join(compat)}) are `-include`d by common.mk.\n"
    return s


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--qnx-ports", default=str(ROOT / "results" / "qnx_ports_names.txt"),
                    help="names already in qnx-ports (build-files ports, conan recipes, org repos), one per line")
    a = ap.parse_args(argv)
    have = {ln.strip().lower() for ln in Path(a.qnx_ports).read_text(encoding="utf-8").splitlines()
            if ln.strip() and not ln.startswith("#")}
    libs = load(ROOT / "campaign.yaml")["libraries"]
    shutil.rmtree(OUT, ignore_errors=True)
    done, skipped = [], []
    for lib in libs:
        n = lib["name"]
        if {n.lower(), "lib" + n.lower(), n.lower().removeprefix("lib")} & have:
            continue
        port = ROOT / "ports" / n
        r = json.loads((port / "report.json").read_text(encoding="utf-8"))
        if r.get("build_system") != "cmake" or r.get("build_result") != "built":
            skipped.append(f"{n} ({r.get('build_system') or 'no build'}, {r.get('build_result')})")
            continue
        c, late, libs_ = flags(port)
        d = OUT / n
        for sub in ("nto-x86_64-o", "nto-aarch64-le"):
            (d / sub).mkdir(parents=True)
            (d / sub / "Makefile").write_text("include ../common.mk\n", encoding="utf-8", newline="\n")
        (d / "Makefile").write_text(MAKEFILE, encoding="utf-8", newline="\n")
        (d / "qnx.nto.toolchain.cmake").write_text(TOOLCHAIN, encoding="utf-8", newline="\n")
        args = "".join(f" \\\n             {x}" for x in lib.get("args", []) + INSTALL_ARGS.get(n, []))
        (d / "common.mk").write_text(COMMON.format(
            name=n, tag=lib["tag"], cflags="".join(f" {x}" for x in c + late), ldflags="", libs=libs_, args=args,
            subdir=f"/{lib['subdir']}" if lib.get("subdir") else ""), encoding="utf-8", newline="\n")
        has_patch = (port / "qnx.patch").exists() and (port / "qnx.patch").stat().st_size > 0
        if has_patch:
            shutil.copy2(port / "qnx.patch", d / "qnx.patch")
        compat = sorted(p.name for p in (port / "qnx-compat").glob("*.h")) if (port / "qnx-compat").is_dir() else []
        if compat:
            shutil.copytree(port / "qnx-compat", d / "qnx-compat")
        (d / "README.md").write_text(readme(lib, r, has_patch, compat), encoding="utf-8", newline="\n")
        done.append(n)
    print(f"{len(done)} recipes -> {OUT.relative_to(ROOT)}: {', '.join(done)}")
    print(f"not emitted (only CMake ports that built are): {', '.join(skipped) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
