"""Write docs/MODEL_STEP.md from results/model_eval.csv and ports-model/*/. Never edit it by hand.

    python3 scripts/model_md.py
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TAP_LINE = re.compile(r"^FAIL\s+(\S+) \(exit \d+\); its own subtests \(TAP\): (\d+) ok, (\d+) not ok, (\d+) skipped", re.M)

HEAD = """# The language-model step, measured

qnx-porter fixes most errors with deterministic rules. For an error no rule covers, an optional step asks a
language model for a unified diff. The diff is applied only if `git apply --check` accepts it, and it is
**kept only if a rebuild clears the error**; otherwise it is reverted and recorded as reverted. The model's
endpoint, model name and key come from environment variables only (see SETUP.md). None of them is stored in
the repository or in any report.

`scripts/model_eval.py` re-ports, with the model step on, every library that the rules-only campaign could not
build. The published numbers use the 2024 pins (`--campaign campaign-2024.yaml`) and the x86_64 QEMU target.
The table is generated by `scripts/model_md.py` from `results/model_eval.csv`.
"""

COMPARE = """
## Does the model's fix match what QNX-aware engineers did?
The model never saw these upstream changes. They are compared here after the fact.

**libuv `src/unix/qnx.c`.** QNX 8.0 removed `qtime_entry.nsec` and renamed the syspage entry `new_cpuinfo` to
`cpuinfo`. Upstream libuv's own QNX change,
[PR #4801 "Improved QNX support"](https://github.com/libuv/libuv/pull/4801) (merged 30 June 2025, after the
v1.49.2 we ported), makes the same two changes the model made:
- `uv_uptime()` reads `clock_gettime(CLOCK_MONOTONIC)` and returns `UV__ERR(errno)` on failure. Upstream keeps
  whole seconds; the model's version also adds the nanoseconds.
- `_SYSPAGE_ENTRY(_syspage_ptr, new_cpuinfo)` becomes `cpuinfo`. Upstream guards this with
  `#if __QNX__ >= 800`.

The model's patch: [`ports-model/libuv/patches/`](../ports-model/libuv/patches/).

**libwebsockets `lib/plat/unix/private-lib-plat-unix.h`.** QNX 8.0's `<netinet/tcp.h>` already defines
`TCP_KEEPIDLE`, `TCP_KEEPINTVL` and `TCP_KEEPCNT`, and has no `TCPCTL_KEEPCNT`. The model keeps the old
`TCPCTL_*` fallback only where those are missing. QNX's own libwebsockets port (`qnx-ports/libwebsockets`,
"Adding support for QNX SDP8") changes the same lines, replacing them with `#include <sys/param.h>`
([survey](related/qnx-ports-survey.md)).
"""


def main() -> int:
    rows = list(csv.DictReader((ROOT / "results" / "model_eval.csv").open(encoding="utf-8")))
    out = [HEAD, "\n| Library | Rules only | Rules + model | Tests on QNX 8.0 | Model patches kept / reverted | "
                 "Rule patches | Model calls | Tokens in / out | Model time |\n|---|---|---|---|---|---|---|---|---|\n"]
    for r in rows:
        log = ROOT / "ports-model" / r["library"] / "logs" / "tests.log"
        tests = r["rules_model_tests"]
        if log.exists() and (m := TAP_LINE.search(log.read_text(encoding="utf-8", errors="replace"))):
            tests += f" binaries; its own subtests: {m[2]} ok, {m[3]} not ok, {m[4]} skipped"
        elif tests == "0/0":
            tests = "no tests registered by its default build"
        out.append(f"| [{r['library']}](../ports-model/{r['library']}/REPORT.md) | {r['rules_only_build']} | "
                   f"{r['rules_model_build']} | {tests} | {r['model_patches_kept']} / {r['model_patches_reverted']} | "
                   f"{r['rule_patches']} | {r['model_calls']} | {r['tokens_in']} / {r['tokens_out']} | "
                   f"{r['model_seconds']} s |\n")
    built = sum(r["rules_model_build"] == "built" for r in rows)
    out.append(f"\nWith the model step, {built} of the {len(rows)} libraries the rules could not build now build. "
               f"Model patches kept: {sum(int(r['model_patches_kept']) for r in rows)}, reverted: "
               f"{sum(int(r['model_patches_reverted']) for r in rows)}.\n")
    out.append(COMPARE)
    out.append("""
## Limits
- Two libraries. libgpiod and can-utils were not included: they use Linux-only kernel interfaces, and no fix
  makes them QNX programs.
- A model's answer can differ from run to run. Each run's patches and reasons are in `ports-model/<lib>/`; the
  table shows the latest run.
- libuv's test suite refuses to run as root, so it runs as `qnxuser` through QNX's `on -u` (`run_as` in the
  campaign file). Its failing subtests are named in `ports-model/libuv/logs/tests.log`.
""")
    dest = ROOT / "docs" / "MODEL_STEP.md"
    dest.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"-> {dest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
