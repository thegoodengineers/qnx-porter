"""Write docs/rust/CRATES.md from results/crates*.csv and ports-rust*/<crate>/report.json. Never edit it by hand.

    python3 scripts/crates_md.py
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARCHES = [("x86_64", "results/crates.csv", "ports-rust", "x86_64 (QEMU, KVM)"),
          ("aarch64le", "results/crates-aarch64le.csv", "ports-rust-aarch64le", "aarch64 on QEMU `virt` (emulated)")]

INTRO = """# Rust crates on QNX 8.0

`qnx-porter crate <name> --version <v>` ports a crate from crates.io to QNX 8.0 and runs the crate's own test
binaries on a QNX target. Rust's QNX 8.0 targets (`x86_64-pc-qnx`, `aarch64-unknown-qnx`) are Tier 3, so cargo
builds the standard library with `-Zbuild-std` and links with the SDP's `qcc`
([rustc book](https://doc.rust-lang.org/nightly/rustc/platform-support/nto-qnx.html); our check that this works:
[GATE.md](GATE.md)). The crate's own code is never edited. Fixes go into its dependencies:

- **`libc-update`.** A published crate's `Cargo.lock` often pins a `libc` release older than libc's QNX 8.0
  support. The rule runs `cargo update` on libc within the same semver range.
- **`nto-to-qnx`.** Many dependencies support QNX 7 (`target_os = "nto"`) but not QNX 8.0 (`target_os = "qnx"`).
  The rule vendors a copy where `target_os = "nto"` becomes `any(target_os = "nto", target_os = "qnx")` and
  applies it through cargo's `[patch]` table. Whether the QNX 7 code path is right on QNX 8.0 is shown by the tests
  below, not assumed. getrandom's own tests (which use `/dev/urandom`) pass, and so do the suites of crates that
  depend on it.

Every change is a patch file with its reason in `ports-rust*/<crate>/patches/`. The tables are generated by
`scripts/crates_md.py` from `results/crates*.csv`; run logs are in `results/runs/crates-*.log`.
"""


def table(arch: str, csv_path: str, ports: str, label: str) -> str:
    rows = list(csv.DictReader((ROOT / csv_path).open(encoding="utf-8")))
    ran = [r for r in rows if r["tests_total"] not in ("", "0")]
    built = sum(r["build_result"] == "built" for r in rows)
    out = [f"\n## {label}\n",
           f"{built} of {len(rows)} crates built; {sum(int(r['tests_passed']) for r in ran)} of "
           f"{sum(int(r['tests_total']) for r in ran)} of their own tests passed on QNX 8.0 "
           f"({len(ran)} crates with tests that ran).\n",
           "\n| Crate | Version | Build | Tests on QNX 8.0 | Ignored | Rule fixes | Note |\n|---|---|---|---|---|---|---|\n"]
    for r in sorted(rows, key=lambda r: r["crate"].lower()):
        rep = ROOT / ports / r["crate"] / "report.json"
        fixes = ""
        if rep.exists():
            ps = json.loads(rep.read_text(encoding="utf-8")).get("patches") or []
            fixes = ", ".join(f"{p['rule']} ({p['dep']})" for p in ps)
        tests = f"{r['tests_passed']}/{r['tests_total']}" if r["tests_total"] not in ("", "0") else "none ran"
        note = r["note"] or (r["first_error"][:90] if r["build_result"] != "built" else "")
        out.append(f"| [{r['crate']}]({'../../' + ports}/{r['crate']}/REPORT.md) | {r['version']} | {r['build_result']} "
                   f"| {tests} | {r['tests_ignored'] or ''} | {fixes} | {note} |\n")
    return "".join(out)


def summary(arch: str, csv_path: str, ports: str, label: str) -> str:
    rows = list(csv.DictReader((ROOT / csv_path).open(encoding="utf-8")))
    ran = [r for r in rows if r["tests_total"] not in ("", "0")]
    return (f"- {label}: {sum(r['build_result'] == 'built' for r in rows)} of {len(rows)} crates built; "
            f"{sum(int(r['tests_passed']) for r in ran)} of {sum(int(r['tests_total']) for r in ran)} of their own "
            f"tests passed ({len(ran)} crates with tests that ran)\n")


def readme() -> None:
    """Fill README's <!-- crates:start --> ... <!-- crates:end --> section from the same CSVs."""
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    start, end = "<!-- crates:start -->\n", "<!-- crates:end -->"
    if start in text and end in text:
        body = "".join(summary(*a) for a in ARCHES if (ROOT / a[1]).exists())
        text = text[:text.index(start) + len(start)] + body + text[text.index(end):]
        path.write_text(text, encoding="utf-8", newline="\n")


def main() -> int:
    readme()
    text = INTRO + "".join(table(*a) for a in ARCHES if (ROOT / a[1]).exists())
    dest = ROOT / "docs" / "rust" / "CRATES.md"
    dest.write_text(text + FAILURES, encoding="utf-8", newline="\n")
    print(f"-> {dest.relative_to(ROOT)}")
    return 0


FAILURES = """
## What the failing tests are
Each was read in `ports-rust*/<crate>/logs/tests.log`. None points at a broken port:
- **chrono:** 8 tests in `lib:chrono` read Android and HarmonyOS time-zone database files, which do not exist on
  QNX (`NotFound`). One more test, `win_bindings`, checks Windows bindings. Both architectures.
- **serde_json** (`compiletest`): a `trybuild` test that compiles code at test time. The target has no Rust
  compiler.
- **tempfile** (`namedtempfile`): on this QNX image `/tmp` is a link to `/data/var/tmp`, so a canonical path
  differs from the expected one. The second failure is a `PoisonError` that follows from the first.
- **crossbeam-channel** (x86_64 only): `golang::select2` asserts that heap allocations stay under a bound while
  threads run. It fails on x86_64 and passes on aarch64. Not investigated yet.
- **mio** builds, but its tests need cargo features (`os-poll`, `net`) that a default build leaves off, so none
  ran.
- **regex** and **zstd** are built as libraries only: their published crates do not include the files their
  tests read.
- **nix** does not build. It needs QNX 8.0 errno support beyond the `nto-to-qnx` rule.
"""

if __name__ == "__main__":
    sys.exit(main())
