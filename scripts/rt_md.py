"""Write docs/RT_RESULTS.md from results/rt.csv and results/rt_scan.csv. Never edit it by hand.

    python3 scripts/rt_md.py
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

HEAD = """# Real-time readiness: results

How the scan and the measurement work: [RT_READINESS.md](RT_READINESS.md). This page is generated by
`scripts/rt_md.py` from `results/rt.csv` and `results/rt_scan.csv`; per library, the full record is in
`results/rt/<arch>/<lib>.json`.

**Read this first.** The latencies were measured on QNX 8.0 running in QEMU (x86_64, KVM) on a laptop. A
virtual CPU can be descheduled by the host at any moment, so absolute numbers, and especially maxima, say
little about real hardware. Even idle p99 is sometimes above loaded p99 here (see below), which on a dedicated
core would be unusual. Use the table to compare libraries with each other and to see where QNX's CPU isolation
(runmask) makes a difference, not as a latency guarantee.
"""


def f(x: str) -> str:
    return x if x else "–"


def main() -> int:
    rows = list(csv.DictReader((ROOT / "results" / "rt.csv").open(encoding="utf-8")))
    done = [r for r in rows if not r["error"]]
    out = [HEAD, f"\n## Latency of one call, microseconds ({len(done)} libraries measured)\n",
           "Each call ran {n} times, idle, under load (load threads on every CPU) and under load with the measuring "
           "thread isolated by runmask. SCHED_FIFO priority 60.\n\n".format(
               n=done[0]["iterations"] if done else "–"),
           "| Library | Call | p99 idle | p99 loaded | p99 loaded, isolated | max loaded | static score | rt score |\n",
           "|---|---|---|---|---|---|---|---|\n"]
    for r in sorted(done, key=lambda r: r["library"].lower()):
        out.append(f"| {r['library']} | {r['call']} | {f(r['idle_p99_us'])} | {f(r['loaded_p99_us'])} | "
                   f"{f(r['loaded_isolated_p99_us'])} | {f(r['loaded_max_us'])} | {f(r['static_score'])} | "
                   f"{f(r['rt_score'])} |\n")
    helped = [r for r in done if r["loaded_p99_us"] and r["loaded_isolated_p99_us"]
              and float(r["loaded_isolated_p99_us"]) < 0.5 * float(r["loaded_p99_us"])]
    noisy = [r["library"] for r in done if r["idle_p99_us"] and r["loaded_p99_us"]
             and float(r["idle_p99_us"]) > float(r["loaded_p99_us"])]
    out.append("\n## What the measurements show\n")
    out.append("- Isolation at least halved loaded p99 for: "
               + (", ".join(f"{r['library']} ({r['loaded_p99_us']} to {r['loaded_isolated_p99_us']} us)" for r in helped)
                  or "none") + ".\n")
    out.append("- Idle p99 above loaded p99, a sign of QEMU timing noise rather than of the library: "
               + (", ".join(noisy) or "none") + ".\n")
    errs = [r for r in rows if r["error"]]
    if errs:
        out.append("- Not measured: " + "; ".join(f"{r['library']} ({r['error'].split(':')[0]})" for r in errs) + ".\n")
    scan = list(csv.DictReader((ROOT / "results" / "rt_scan.csv").open(encoding="utf-8")))
    out.append(f"\n## Static scan ({len(scan)} libraries)\n`results/rt_scan.csv`; the categories and the score are "
               "explained in [RT_READINESS.md](RT_READINESS.md).\n")
    dest = ROOT / "docs" / "RT_RESULTS.md"
    dest.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"-> {dest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
